#!/usr/bin/env python3
"""路由生成器：从技能 frontmatter + meta/routing.yaml 生成路由表与前置声明。

用法：
  python tools/gen_router.py            # 写入 routing.generated.md + 各技能 preamble
  python tools/gen_router.py --check    # 只校验，不一致退出 1
  python tools/gen_router.py --dry-run  # 列出将变更的文件
"""
import argparse
import re
import sys
import pathlib

try:
    import yaml
except ImportError:
    sys.exit("需要 PyYAML：pip install pyyaml（仅开发/CI 依赖）")

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"
ROUTING_YAML = ROOT / "meta" / "routing.yaml"

BEGIN = "<!-- BEGIN GENERATED PREAMBLE -->"
END = "<!-- END GENERATED PREAMBLE -->"


def read_frontmatter(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"(?s)^---\n(.*?)\n---\n", text)
    if not m:
        raise SystemExit("缺少 frontmatter: %s" % path)
    return yaml.safe_load(m.group(1)) or {}


def load_skills():
    skills = {}
    for d in sorted(p for p in SKILLS.iterdir() if p.is_dir()):
        md = d / "SKILL.md"
        if md.exists():
            skills[d.name] = read_frontmatter(md)
    return skills


def phase_key(name, meta, phase_order):
    phases = [x.strip() for x in str(meta.get("metadata", {}).get("phase", "")).split(",") if x.strip()]
    order = len(phase_order)
    for p in phases:
        if p in phase_order:
            order = min(order, phase_order.index(p))
    return (order, name)


def gen_routing_md(skills, routing):
    mandatory = routing["mandatory"]
    phase_order = routing["phase_order"]
    entry = routing["entry"]

    lines = [
        "<!-- DO NOT EDIT: generated by tools/gen_router.py -->",
        "# 技能路由（生成物）",
        "",
        "> 本文件由 `tools/gen_router.py` 生成。修改技能 frontmatter 后运行：",
        "> `python tools/gen_router.py && python tools/gen_router.py --check`",
        "",
        "## 强制门禁（缺行不得进入对应阶段）",
        "",
        "| 观察到的信号 | 加载 | 依据 |",
        "|---|---|---|",
    ]
    for name in mandatory:
        if name not in skills:
            raise SystemExit("mandatory 技能不存在: %s" % name)
        meta = skills[name].get("metadata", {})
        trig = meta.get("triggers") or []
        if not trig:
            raise SystemExit("mandatory 技能缺 triggers: %s" % name)
        signal = trig[0]
        basis = trig[1] if len(trig) > 1 else "—"
        lines.append("| %s | `%s` | %s |" % (signal, name, basis))

    lines += [
        "",
        "## 建议加载（信号出现才加载）",
        "",
        "**加载前先判断缺口**：已加载技能正文能否支撑当前动作？能则不加载知识型技能。已加载的直接复用，不重复记行。",
        "",
        "| 观察到的信号 / 当前动作 | 加载 |",
        "|---|---|",
    ]
    rest = [n for n in skills if n != entry and n not in mandatory]
    rest.sort(key=lambda n: phase_key(n, skills[n], phase_order))
    for name in rest:
        trig = skills[name].get("metadata", {}).get("triggers") or []
        signal = "；".join(trig)
        lines.append("| %s | `%s` |" % (signal, name))

    lines += [
        "",
        "## 技能清单（%d）" % len(skills),
        "",
        "| 技能 | 版本 | 前置 | 阶段 |",
        "|---|---|---|---|",
    ]
    ordered = [entry] + [n for n in mandatory if n != entry] + rest
    for name in ordered:
        meta = skills[name].get("metadata", {})
        req = ", ".join(meta.get("requires") or []) or "—"
        lines.append("| %s | %s | %s | %s |"
                     % (name, meta.get("version", "?"), req,
                        meta.get("phase", "?")))
    lines.append("")
    return "\n".join(lines)


def gen_preamble(name):
    if name == "pentest-flow":
        return None
    return (
        BEGIN + "\n"
        "> **前置**：本技能不构成授权依据。首次加载先读\n"
        "> `../pentest-flow/references/constitution.md` §1–§8；产物写入 `Work/OC-<target>/`。\n"
        "> 路由与门禁见 `../pentest-flow/SKILL.md`。\n"
        + END
    )


def apply_preamble(text, block):
    if not block:
        return text
    if BEGIN in text:
        return re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), block, text, flags=re.S)
    # 插入到第一个一级标题之后
    m = re.search(r"(?m)^# .*$", text)
    if m:
        return text[:m.end()] + "\n\n" + block + text[m.end():]
    return text.rstrip() + "\n\n" + block + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    routing = yaml.safe_load(ROUTING_YAML.read_text(encoding="utf-8"))
    skills = load_skills()
    routing_md = gen_routing_md(skills, routing)

    out_path = ROOT / routing["output"]["file"]
    changes = []

    current = out_path.read_text(encoding="utf-8") if out_path.exists() else ""
    if current != routing_md:
        changes.append(out_path)

    preambles = {}
    for name in skills:
        md = SKILLS / name / "SKILL.md"
        text = md.read_text(encoding="utf-8")
        block = gen_preamble(name)
        new = apply_preamble(text, block)
        if new != text:
            preambles[md] = new
            changes.append(md)

    if args.check:
        if changes:
            print("FAIL: %d file(s) out of date" % len(changes))
            for p in changes:
                print("-", p.relative_to(ROOT))
            return 1
        print("PASS: routing.generated.md 与 preambles 均为最新")
        return 0

    if args.dry_run:
        print("将变更 %d 个文件：" % len(changes))
        for p in changes:
            print("-", p.relative_to(ROOT))
        return 0

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(routing_md, encoding="utf-8", newline="\n")
    for md, text in preambles.items():
        md.write_text(text, encoding="utf-8", newline="\n")
    print("已生成: %s" % out_path.relative_to(ROOT))
    print("已更新 preamble: %d 个技能" % len(preambles))
    return 0


if __name__ == "__main__":
    sys.exit(main())
